// Link-opportunity finder (F-06). Heuristic sources, all labeled as such:
//  - 'reclaim': lost backlinks that could be restored by outreach.
//  - 'unlinked-mention': domains that cited/mentioned the brand in AI-answer
//    simulations (geo_checks) but have no recorded backlink.
// No external provider is consulted; results are opportunities to review,
// not measured link prospects.

import type { QueryFn } from '../db.js';
import { query as defaultQuery } from '../db.js';

export interface LinkOpportunity {
  id: string;
  source_url: string;
  source_domain: string;
  kind: 'reclaim' | 'unlinked-mention';
  reason: string;
  created_at: string;
}

function domainOf(url: string): string | null {
  try {
    return new URL(url).hostname.toLowerCase().replace(/^www\./, '');
  } catch {
    return null;
  }
}

/**
 * Refresh the site's link opportunities (idempotent upsert).
 * Returns the fresh list.
 */
export async function findLinkOpportunities(
  tenantId: string,
  siteId: string,
  q: QueryFn = defaultQuery,
): Promise<LinkOpportunity[]> {
  // Known referring domains (have a link already) — excluded from unlinked mentions.
  const known = new Set<string>();
  const knownR = await q(
    `SELECT DISTINCT referring_domain FROM backlinks
     WHERE site_id = $1 AND tenant_id = $2 AND referring_domain IS NOT NULL`,
    [siteId, tenantId],
  );
  for (const row of knownR.rows as Array<{ referring_domain: string }>) {
    known.add(row.referring_domain.replace(/^www\./, ''));
  }

  const site = await q(`SELECT domain FROM sites WHERE id = $1 AND tenant_id = $2`, [siteId, tenantId]);
  const siteDomain = ((site.rows[0]?.domain as string | undefined) ?? '').toLowerCase();

  const upserts: Array<{ url: string; domain: string; kind: 'reclaim' | 'unlinked-mention'; reason: string }> = [];

  // 1. Reclaim: lost links.
  const lost = (
    await q(
      `SELECT source_url, last_seen FROM backlinks
       WHERE site_id = $1 AND tenant_id = $2 AND status = 'lost' LIMIT 100`,
      [siteId, tenantId],
    )
  ).rows as Array<{ source_url: string; last_seen: string }>;
  for (const l of lost) {
    const d = domainOf(l.source_url);
    if (!d) continue;
    upserts.push({
      url: l.source_url,
      domain: d,
      kind: 'reclaim',
      reason: `Link lost (last seen ${l.last_seen}). Reach out to ${d} to restore it — reclaimed links are the cheapest wins.`,
    });
  }

  // 2. Unlinked mentions: domains cited in simulated AI answers that
  // mentioned the brand but are not recorded backlinks.
  const checks = (
    await q(
      `SELECT citations FROM geo_checks
       WHERE site_id = $1 AND tenant_id = $2 AND mentioned = TRUE
         AND checked_at > now() - interval '90 days' LIMIT 200`,
      [siteId, tenantId],
    )
  ).rows as Array<{ citations: { sources?: string[]; brands?: Record<string, boolean> } | null }>;
  const mentionCounts = new Map<string, number>();
  for (const c of checks) {
    for (const src of c.citations?.sources ?? []) {
      const d = src.toLowerCase().replace(/^www\./, '');
      if (!d || d === siteDomain || known.has(d)) continue;
      mentionCounts.set(d, (mentionCounts.get(d) ?? 0) + 1);
    }
  }
  for (const [d, n] of [...mentionCounts.entries()].sort((a, b) => b[1] - a[1]).slice(0, 50)) {
    upserts.push({
      url: `https://${d}/`,
      domain: d,
      kind: 'unlinked-mention',
      reason: `Mentioned your brand in ${n} simulated AI answer(s) but has no recorded backlink. Pitch a linkable asset or ask for attribution. (Heuristic — verify the mention is real.)`,
    });
  }

  // D1-M-3: batch the upserts with unnest() instead of one INSERT per
  // opportunity (up to ~150 sequential round-trips before).
  if (upserts.length > 0) {
    await q(
      `INSERT INTO link_opportunities (tenant_id, site_id, source_url, source_domain, kind, reason)
       SELECT $1, $2, unnest($3::text[]), unnest($4::text[]), unnest($5::text[]), unnest($6::text[])
       ON CONFLICT (site_id, source_url, kind) DO UPDATE SET reason = EXCLUDED.reason`,
      [tenantId, siteId, upserts.map((u) => u.url), upserts.map((u) => u.domain), upserts.map((u) => u.kind), upserts.map((u) => u.reason)],
    );
  }

  const list = await q(
    `SELECT id, source_url, source_domain, kind, reason, created_at FROM link_opportunities
     WHERE site_id = $1 AND tenant_id = $2 ORDER BY created_at DESC LIMIT 100`,
    [siteId, tenantId],
  );
  return list.rows as LinkOpportunity[];
}

/**
 * Pure: build a Google disavow file from toxic backlinks.
 * Uses domain: directives for toxic domains. Includes a header comment
 * labeling the heuristic source.
 */
export function buildDisavowFile(links: Array<{ source_url: string; toxic_score: number }>): string {
  const domains = new Set<string>();
  for (const l of links) {
    const d = domainOf(l.source_url);
    if (d) domains.add(d);
  }
  const lines = [
    '# Disavow file generated by Beyonix SEO.',
    '# Sources were flagged by HEURISTIC scoring only (see toxic_flags) — review before uploading to Google Search Console.',
    '# Format: https://support.google.com/webmasters/answer/2648487',
    '',
  ];
  for (const d of [...domains].sort()) lines.push(`domain:${d}`);
  lines.push('');
  return lines.join('\n');
}
