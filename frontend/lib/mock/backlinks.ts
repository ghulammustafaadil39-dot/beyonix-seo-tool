/** Build a Google disavow file from a list of domains (client-side). */
export function buildDisavowFile(domains: string[]): string {
  const lines = [
    '# Disavow file generated by Beyonix SEO',
    `# ${new Date().toISOString().slice(0, 10)}`,
    '',
  ];
  for (const d of domains) lines.push(`domain:${d.trim().toLowerCase()}`);
  return lines.join('\n') + '\n';
}

export function downloadTextFile(filename: string, text: string): void {
  const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
